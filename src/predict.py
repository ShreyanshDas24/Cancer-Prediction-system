"""Inference and diagnostic risk categorization service.

EDUCATIONAL DISCLAIMER:
    This software is developed strictly for educational and scientific research purposes.
    It does NOT provide medical diagnoses, clinical guidance, or treatment recommendations.
    All outputs represent statistical estimates generated by a machine-learning model
    trained on the 1995 Wisconsin Diagnostic Breast Cancer dataset.
"""

from typing import Dict, Any, List, Union, Optional
import os
import json
import joblib
import numpy as np
import pandas as pd

from src.data_loader import MALIGNANT_LABEL, BENIGN_LABEL, LABEL_NAMES

MODEL_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "models")
BEST_MODEL_PATH = os.path.join(MODEL_DIR, "best_model.joblib")
ALL_MODELS_PATH = os.path.join(MODEL_DIR, "all_models.joblib")
METADATA_PATH = os.path.join(MODEL_DIR, "feature_metadata.json")


class CancerPredictor:
    """Inference engine for the 15-feature production pipeline."""

    def __init__(self, model_name: Optional[str] = None):
        self.metadata = self._load_metadata()
        self.selected_features = list(self.metadata.keys())
        self.models_dict = self._load_all_models()

        if model_name and model_name in self.models_dict:
            self.model_name = model_name
            self.pipeline = self.models_dict[model_name]
        else:
            self.pipeline = joblib.load(BEST_MODEL_PATH)
            self.model_name = "Champion Model"

    def _load_metadata(self) -> Dict[str, Any]:
        if not os.path.exists(METADATA_PATH):
            raise FileNotFoundError(f"Feature metadata not found at {METADATA_PATH}. Run train_model.py first.")
        with open(METADATA_PATH, "r") as f:
            return json.load(f)

    def _load_all_models(self) -> Dict[str, Any]:
        if os.path.exists(ALL_MODELS_PATH):
            return joblib.load(ALL_MODELS_PATH)
        return {}

    def set_model(self, model_name: str) -> None:
        """Switches the active model for comparative predictions."""
        if model_name not in self.models_dict:
            raise ValueError(f"Model '{model_name}' not found. Available: {list(self.models_dict.keys())}")
        self.model_name = model_name
        self.pipeline = self.models_dict[model_name]

    def validate_input(self, input_data: Union[Dict[str, float], pd.DataFrame]) -> pd.DataFrame:
        """Validates that all 15 required features are provided with valid numeric values."""
        if isinstance(input_data, dict):
            df = pd.DataFrame([input_data])
        else:
            df = input_data.copy()

        missing = [f for f in self.selected_features if f not in df.columns]
        if missing:
            raise ValueError(f"Missing required features: {missing}")

        # Keep exact 15-feature ordering
        df = df[self.selected_features]

        # Check for non-numeric or NaN values
        for col in self.selected_features:
            df[col] = pd.to_numeric(df[col], errors="coerce")
            if df[col].isnull().any():
                raise ValueError(f"Feature '{col}' contains invalid or non-numeric values.")

        return df

    def predict_sample(self, input_data: Union[Dict[str, float], pd.DataFrame]) -> Dict[str, Any]:
        """Performs full statistical evaluation for a sample.

        Returns:
            result (dict):
                - predicted_label: int (0 or 1)
                - predicted_class: str ("Malignant" or "Benign")
                - proba_malignant: float
                - proba_benign: float
                - confidence: float
                - risk_category: str ("Very Low", "Low", "Intermediate", "Elevated", "High")
                - feature_deviations: dict of z-scores relative to benign cohort
                - model_used: str
                - disclaimer: str
        """
        df = self.validate_input(input_data)

        # Scikit-learn raw prediction
        pred_label = int(self.pipeline.predict(df)[0])
        pred_class = LABEL_NAMES[pred_label]

        # Probability calculation
        if hasattr(self.pipeline, "predict_proba"):
            proba = self.pipeline.predict_proba(df)[0]
            # In sklearn: index 0 = malignant, index 1 = benign
            p_malignant = float(proba[MALIGNANT_LABEL])
            p_benign = float(proba[BENIGN_LABEL])
        else:
            # Fallback for models without direct probability calibration
            p_malignant = 1.0 if pred_label == MALIGNANT_LABEL else 0.0
            p_benign = 1.0 - p_malignant

        # Confidence is probability associated with predicted class
        confidence = p_malignant if pred_label == MALIGNANT_LABEL else p_benign

        # Model Risk Category (Educational stratification)
        risk_category = self._categorize_risk(p_malignant)

        # Feature deviations: z-scores relative to benign population
        deviations = {}
        sample_dict = df.iloc[0].to_dict()
        for feat in self.selected_features:
            val = float(sample_dict[feat])
            b_mean = self.metadata[feat]["benign_mean"]
            b_std = self.metadata[feat]["benign_std"]
            z_score = (val - b_mean) / b_std if b_std > 0 else 0.0
            deviations[feat] = {
                "value": round(val, 4),
                "benign_median": round(self.metadata[feat]["benign_median"], 4),
                "malignant_median": round(self.metadata[feat]["malignant_median"], 4),
                "z_score_vs_benign": round(z_score, 2),
                "unit": self.metadata[feat]["unit"],
                "category": self.metadata[feat]["category"],
            }

        return {
            "predicted_label": pred_label,
            "predicted_class": pred_class,
            "proba_malignant": round(p_malignant, 4),
            "proba_benign": round(p_benign, 4),
            "confidence_percentage": round(confidence * 100, 2),
            "model_risk_category": risk_category,
            "feature_deviations": deviations,
            "model_used": self.model_name,
            "disclaimer": (
                "EDUCATIONAL DISCLAIMER: This model is for academic and demonstration purposes only. "
                "It does not constitute medical advice or clinical diagnosis. Do not use for healthcare decisions."
            ),
        }

    @staticmethod
    def _categorize_risk(p_malignant: float) -> str:
        """Stratifies predicted malignancy probability into educational risk tiers."""
        if p_malignant < 0.10:
            return "Very Low"
        elif p_malignant < 0.35:
            return "Low"
        elif p_malignant < 0.65:
            return "Intermediate"
        elif p_malignant < 0.85:
            return "Elevated"
        else:
            return "High"


if __name__ == "__main__":
    predictor = CancerPredictor()
    print(f"Loaded predictor using: {predictor.model_name}")
    print(f"Selected features count: {len(predictor.selected_features)}")

    # Test with median benign sample from metadata
    sample_benign = {f: predictor.metadata[f]["benign_median"] for f in predictor.selected_features}
    res_b = predictor.predict_sample(sample_benign)
    print("\nBenign Median Test:")
    print(f"  Predicted: {res_b['predicted_class']} (Prob Malignant: {res_b['proba_malignant']:.4f}, Risk: {res_b['model_risk_category']})")

    # Test with median malignant sample from metadata
    sample_mal = {f: predictor.metadata[f]["malignant_median"] for f in predictor.selected_features}
    res_m = predictor.predict_sample(sample_mal)
    print("\nMalignant Median Test:")
    print(f"  Predicted: {res_m['predicted_class']} (Prob Malignant: {res_m['proba_malignant']:.4f}, Risk: {res_m['model_risk_category']})")
